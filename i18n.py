CURRENCY = {"en": "UZS", "ru": "сум", "uz": "so'm"}


def norm(lang: str | None) -> str:
    return lang if lang in LANGS else DEFAULT_LANG


def t(lang: str | None, key: str, **kw) -> str:
    """Translate `key`; falls back to English, then to the key itself. Always injects {line}."""
    lang = norm(lang)
    text = STR[lang].get(key) or STR[DEFAULT_LANG].get(key) or key
    return text.format(line=LINE, **kw) if ("{" in text) else text


def fmt_date(lang: str | None, d: date) -> str:
    lang = norm(lang)
    wd, mo = _WEEKDAYS[lang][d.weekday()], _MONTHS[lang][d.month - 1]
    if lang == "uz":
        return f"{d.day}-{mo} {d.year}, {wd}"
    return f"{wd}, {d.day} {mo} {d.year}"


def fmt_date_short(lang: str | None, d: date) -> str:
    lang = norm(lang)
    mo = _MONTHS[lang][d.month - 1]
    return f"{d.day}-{mo} {d.year}" if lang == "uz" else f"{d.day} {mo} {d.year}"


def money(lang: str | None, value: float) -> str:
    return f"{round(value):,}".replace(",", " ") + " " + CURRENCY[norm(lang)]
